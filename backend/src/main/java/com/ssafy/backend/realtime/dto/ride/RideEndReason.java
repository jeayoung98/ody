package com.ssafy.backend.realtime.dto.ride;

/** 따라가기가 끝난 이유. */
public enum RideEndReason {
	/**
	 * 인솔자가 사라졌다. 창을 닫았거나 접속이 만료됐다.
	 *
	 * 스스로 나간 것과 끊긴 것을 구분하지 않는다. 따라가던 사람이 할 일이 같기 때문이다.
	 * 받는 쪽에서 보면 인솔자는 이제 없는 사람이다.
	 */
	CAPTAIN_LEFT,

	/**
	 * 인솔자가 따라가기를 끝냈다.
	 *
	 * 위와 갈라 둔 이유는 하나다 — 이쪽은 인솔자가 그대로 있다. 같은 곡에 그대로 서 있고,
	 * 다시 따라갈 수도 있다. 받는 쪽이 "나갔다"고 알리면 화면과 어긋난다.
	 *
	 * 남게 되는 자리와 그 뒤에 할 일은 위와 똑같다.
	 */
	CAPTAIN_ENDED
}
