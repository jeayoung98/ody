-- 팔로우 API [S15P21A405-433] — 이미 follow 테이블이 있는 DB 에 실행한다.
--
-- 1) follow.id 를 auto increment 로 바꾼다.
--    지금은 DEFAULT 가 없어 INSERT 할 때마다 id 를 직접 넣어야 한다. IDENTITY 로 바꾸면 DB 가 채운다.
--    기존 행이 있으면 시퀀스 시작값을 최대 id 다음으로 올려야 중복 키가 나지 않는다 — 아래 두 문장을 같이 실행한다.
ALTER TABLE follow ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;

SELECT setval(pg_get_serial_sequence('follow', 'id'), COALESCE(MAX(id), 0) + 1, false) FROM follow;

-- 2) 같은 사람을 두 번 팔로우하지 못하게 막는다.
--    애플리케이션도 INSERT 전에 확인하지만, 동시에 두 번 눌리면 둘 다 통과할 수 있다.
--    중복 행이 이미 있으면 이 문장이 실패한다 — 아래 쿼리로 먼저 확인하고 지운다.
--      SELECT follower_email, followee_email, count(*)
--        FROM follow GROUP BY 1, 2 HAVING count(*) > 1;
ALTER TABLE follow ADD CONSTRAINT uq_follow_pair UNIQUE (follower_email, followee_email);

-- 3) 목록 조회 인덱스.
--    팔로잉 목록은 follower_email 로, 팔로워 목록은 followee_email 로 찾고 created_at 역순으로 정렬한다.
--    uq_follow_pair 가 (follower_email, followee_email) 을 이미 덮으므로 팔로잉 쪽은 정렬 컬럼만 더한다.
--    CONCURRENTLY 는 트랜잭션 안에서 실행할 수 없다. psql 로 한 줄씩 실행한다.
CREATE INDEX CONCURRENTLY IF NOT EXISTS ix_follow_follower_created
    ON follow (follower_email, created_at DESC);

CREATE INDEX CONCURRENTLY IF NOT EXISTS ix_follow_followee_created
    ON follow (followee_email, created_at DESC);

-- 4) 만난 횟수 역방향 조회 인덱스.
--    목록은 요청자와 상대의 meeting 행을 양방향 등호로 찾는다(콜레이션에 기대지 않기 위해서다).
--    meeting 의 PK 는 (user1, user2) 라 user2 로 시작하는 조회는 인덱스를 타지 못한다.
CREATE INDEX CONCURRENTLY IF NOT EXISTS ix_meeting_user2_user1
    ON meeting (user2, user1);
