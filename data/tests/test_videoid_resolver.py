"""videoid 판정 — 네트워크 없이 검색·영상조회 함수를 주입해 검증한다 (S15P21A405-441).

검증 대상은 셋이다.
1. 엄격 검증(스펙 15 매핑 규칙 2, AGENTS.md 규칙 6)을 통과한 곡만 confidence=verified 다.
2. 유사도 추측은 PLAY_THRESHOLD 이상 + embed 가능일 때만 재생 가능으로 판정한다.
3. 판정 불가와 검색 실패를 구분한다.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from videoid.api import resolve_request
from videoid.resolver import GUESS_EMBED_CHECKS, PLAY_THRESHOLD, embeddable, resolve

TRACK = {'title': 'Live For You', 'artist': 'Downhere', 'album': 'Ending Is Beginning',
         'duration': 204, 'release_year': 2008, 'isrc': ''}

OFFICIAL_DESCRIPTION = ('Provided to YouTube by Universal\n\n'
                        'Live For You · Downhere\n'
                        'Ending Is Beginning\n\n'
                        'Auto-generated by YouTube.')


def video(video_id: str, title: str, channel: str, duration: int = 204, **overrides) -> dict:
    base = {'id': video_id, 'title': title, 'channel': channel, 'duration': duration,
            'availability': 'public', 'description': '', 'playable_in_embed': True,
            'is_live': False, 'live_status': 'not_live', 'age_limit': 0}
    base.update(overrides)
    return base


def snippet(video_id: str, title: str, channel: str, duration: int | None = 204) -> dict:
    return {'id': video_id, 'title': title, 'channel': channel, 'duration': duration}


# --- 엄격 검증 -------------------------------------------------------------

def test_official_art_track_is_verified():
    hits = [snippet('ddddddddddd', 'Live For You', 'Downhere - Topic')]
    detail = video('ddddddddddd', 'Live For You', 'Downhere - Topic',
                   description=OFFICIAL_DESCRIPTION)
    result = resolve(TRACK, search_fn=lambda q: hits, video_fn=lambda v: detail)
    assert result['status'] == 'matched_official_art_track'
    assert result['video_id'] == 'ddddddddddd'
    assert result['play_confidence'] == 'verified'
    assert result['playable'] is True


def test_non_embeddable_official_track_is_not_verified():
    """AGENTS.md 규칙 6 — IFrame 임베드가 막힌 영상은 확정하지 않는다."""
    hits = [snippet('ddddddddddd', 'Live For You', 'Downhere - Topic')]
    detail = video('ddddddddddd', 'Live For You', 'Downhere - Topic',
                   description=OFFICIAL_DESCRIPTION, playable_in_embed=False)
    result = resolve(TRACK, search_fn=lambda q: hits, video_fn=lambda v: detail)
    assert result['video_id'] is None
    assert result['play_confidence'] != 'verified'


@pytest.mark.parametrize('overrides', [
    {'playable_in_embed': False},
    {'availability': 'unlisted'},
    {'is_live': True},
    {'live_status': 'is_live'},
    {'age_limit': 18},
])
def test_embeddable_rejects_unplayable_states(overrides):
    assert embeddable(video('x' * 11, 'any', 'any', **overrides)) is False


def test_embeddable_accepts_public_embeddable_video():
    assert embeddable(video('x' * 11, 'any', 'any')) is True


# --- 추측 판정 -------------------------------------------------------------

def test_guess_above_threshold_is_playable_when_it_embeds():
    hits = [snippet('aaaaaaaaaaa', 'Downhere - Live For You (Official Audio)', 'Downhere', 205),
            snippet('bbbbbbbbbbb', 'Totally Unrelated Song', 'Random Uploads', 61)]
    result = resolve(TRACK, search_fn=lambda q: hits,
                     video_fn=lambda v: video(v, 'whatever', 'whoever'))
    assert result['video_id'] is None, '추측은 확정 필드를 채우지 않는다'
    assert result['play_confidence'] == 'best_guess'
    assert result['play_video_id'] == 'aaaaaaaaaaa'
    assert result['play_youtube_url'] == 'https://www.youtube.com/watch?v=aaaaaaaaaaa'
    assert result['best_guess']['score'] >= PLAY_THRESHOLD
    assert result['best_guess']['embed_checked'] is True
    assert result['best_guess']['verified'] is False


def test_guess_below_threshold_is_unplayable():
    weak = snippet('eeeeeeeeeee', 'Live For You (cover by a fan)', 'Karaoke Corner', 250)
    result = resolve(TRACK, search_fn=lambda q: [weak],
                     video_fn=lambda v: video(v, 'whatever', 'whoever'))
    assert result['playable'] is False
    assert result['play_confidence'] == 'unplayable'
    assert result['best_guess'] is None


def test_guess_skips_candidate_that_cannot_embed():
    hits = [snippet('aaaaaaaaaaa', 'Downhere - Live For You (Official Audio)', 'Downhere', 205),
            snippet('ccccccccccc', 'Downhere - Live For You', 'Downhere', 204)]
    blocked = {'aaaaaaaaaaa'}

    def video_fn(video_id: str) -> dict:
        return video(video_id, 'x', 'y', playable_in_embed=video_id not in blocked)

    result = resolve(TRACK, search_fn=lambda q: hits, video_fn=video_fn)
    assert result['play_video_id'] == 'ccccccccccc'


def test_guess_stops_after_the_embed_check_budget():
    hits = [snippet(chr(97 + i) * 11, 'Downhere - Live For You', 'Downhere', 204)
            for i in range(GUESS_EMBED_CHECKS + 3)]
    calls: list[str] = []

    def video_fn(video_id: str) -> dict:
        calls.append(video_id)
        return video(video_id, 'x', 'y', playable_in_embed=False)

    result = resolve(TRACK, search_fn=lambda q: hits, video_fn=video_fn)
    assert result['playable'] is False
    assert len(calls) <= GUESS_EMBED_CHECKS + len(hits), calls


# --- duration 없이 호출 ----------------------------------------------------

def test_missing_duration_still_answers():
    """백엔드 계약에는 duration 이 없다. 없으면 길이 대조만 생략한다."""
    track = dict(TRACK)
    track['duration'] = None
    hits = [snippet('aaaaaaaaaaa', 'Downhere - Live For You (Official Audio)', 'Downhere', None)]
    result = resolve(track, search_fn=lambda q: hits,
                     video_fn=lambda v: video(v, 'x', 'y'))
    assert result['play_confidence'] == 'best_guess'
    assert result['video_id'] is None, 'duration 없이 확정하지 않는다'


def test_missing_title_or_artist_is_rejected():
    with pytest.raises(ValueError):
        resolve({'title': '', 'artist': 'Downhere', 'duration': 204},
                search_fn=lambda q: [], video_fn=lambda v: {})


# --- 실패 구분 -------------------------------------------------------------

def test_search_failure_is_retryable_not_unplayable():
    def boom(query: str):
        raise TimeoutError('search timed out')

    result = resolve(TRACK, search_fn=boom, video_fn=lambda v: {})
    assert result['status'] == 'retry_pending'
    assert result['playable'] is False
    assert result['errors']


def test_empty_search_is_no_candidate():
    result = resolve(TRACK, search_fn=lambda q: [], video_fn=lambda v: {})
    assert result['status'] == 'no_candidate_in_search'
    assert result['playable'] is False


# --- 백엔드 응답 계약 ------------------------------------------------------

def _fake_lookup(result: dict):
    return lambda track, refresh=False: dict(result, cache_hit=False)


def test_backend_contract_shape_for_verified():
    hits = [snippet('ddddddddddd', 'Live For You', 'Downhere - Topic')]
    detail = video('ddddddddddd', 'Live For You', 'Downhere - Topic',
                   description=OFFICIAL_DESCRIPTION)
    resolved = resolve(TRACK, search_fn=lambda q: hits, video_fn=lambda v: detail)
    body = resolve_request('Downhere', 'Live For You', lookup_fn=_fake_lookup(resolved))
    assert body['best']['videoId'] == 'ddddddddddd'
    assert body['best']['confidence'] == 'verified'
    assert body['playable'] is True
    assert body['threshold'] == PLAY_THRESHOLD
    # 백엔드 VideoIdApiResponse 는 best.videoId 만 읽는다. 직렬화가 되는지 확인한다.
    assert json.loads(json.dumps(body))['best']['videoId'] == 'ddddddddddd'


def test_backend_contract_best_is_null_when_unplayable():
    weak = snippet('eeeeeeeeeee', 'Live For You (cover by a fan)', 'Karaoke Corner', 250)
    resolved = resolve(TRACK, search_fn=lambda q: [weak],
                       video_fn=lambda v: video(v, 'x', 'y'))
    body = resolve_request('Downhere', 'Live For You', lookup_fn=_fake_lookup(resolved))
    assert body['best'] is None
    assert body['playable'] is False
    assert body['retryable'] is False


def test_backend_contract_marks_search_failure_retryable():
    def boom(query: str):
        raise TimeoutError('search timed out')

    resolved = resolve(TRACK, search_fn=boom, video_fn=lambda v: {})
    body = resolve_request('Downhere', 'Live For You', lookup_fn=_fake_lookup(resolved))
    assert body['best'] is None
    assert body['retryable'] is True
