/**
 * **떠오른 뒤 내려앉을 배율** (S15P21A405-673).
 *
 * `ascendTo` 는 그 겹을 떠날 때 남긴 진입 배율(`entryS`)로 되돌아간다. 파고든 겹에서는 그게 맞다 —
 * `deepFit` 이 상주 상자를 화면의 90%로 맞춘 값이라 이미 화면이 차고, 그 아래로 내려가는 건
 * 떠오르기로 처리해야 할 동작이라 진입 배율이 곧 축소 한계다(`DRILL.deepZoomOutRatio`).
 *
 * **0겹만 다르다.** 0겹의 `entryS` 는 거리 97분위를 화면 짧은 변 44% 반지름에 넣는
 * 반지름 맞춤인데, 상주 집합의 상자는 거의 정사각이고 화면은 2배 넘게 가로로 길다.
 * S15P21A405-469 가 이걸 실측해 뒀다 — **가로 30% · 세로 62% 만 차고 좌우가 통째로 비었다.**
 * 469 는 그래서 첫 화면(`startCam0`)을 긴 쪽을 채우는 배율로 열게 고쳤는데, **떠오르는 길은
 * 그대로 뒀다.** 그래서 우주로 돌아오면 469 가 고친 그 줌아웃 화면이 다시 나왔다.
 *
 * 고치는 건 **착지 카메라의 배율뿐이고 `entryS` 는 건드리지 않는다.** 줌 한계(`zoomRange`)·
 * 파고들기 임계(`gateMinZoom`)·떠오르기 압력(`riseScaleRatio`)이 전부 `entryS` 대비라, 그걸 같이
 * 조이면 "줌아웃해서 전체를 본다" 가 막히고 파고들기 임계까지 그만큼 깊어진다 (469 의 근거 그대로).
 * 휠을 뒤로 굴리면 예전처럼 전역이 들어온다.
 */

/**
 * 떠오르기 착지 배율. `layer` 는 **도착할** 겹이다.
 *
 * `Math.max` 인 이유: 두 배율은 서로 다른 식(반지름 맞춤 vs 상자 덮기)에서 나와 대소가 보장되지
 * 않는다. 덮는 배율이 더 작게 나오는 상주 집합이 있으면 그걸 쓰는 순간 **자동으로 줌아웃된
 * 화면으로 착지**하게 되는데, 그게 이 이슈가 없애려는 바로 그 동작이다.
 */
export function riseLandingScale(layer: number, entryS: number, coverS: number): number {
  if (layer !== 0) return entryS;
  if (!Number.isFinite(coverS) || coverS <= 0) return entryS;
  return Math.max(entryS, coverS);
}
