/**
 * 이 자리를 받아도 되는가.
 *
 * **날아가는 중이 아니면 늘 받는다.** 따라가기(`RIDE_TRACK`)·하차처럼 비행 없이 자리만
 * 정해지는 길이 그렇고, 그때는 서버가 준 값이 유일한 근거다.
 *
 * 날아가는 중이면 **그 목적지와 같을 때만** 받는다. 다른 곡이면 옛 자리다.
 */
export function acceptsAnchor(travelingTo: number | null, incoming: number): boolean {
  return travelingTo == null || travelingTo === incoming;
}
